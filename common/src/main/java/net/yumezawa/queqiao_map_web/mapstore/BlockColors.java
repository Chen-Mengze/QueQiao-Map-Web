    /**
     * 取色：palette entry 的 Name（含 Properties 不影响；不带命名空间时按 minecraft: 补齐）。
     */
    public static int colorOf(String stateName) {
        if (stateName == null) return FALLBACK_GRAY;
        int bar = stateName.indexOf('[');
        if (bar >= 0) stateName = stateName.substring(0, bar);
        Integer c = TABLE.get(stateName);
        if (c == null && stateName.indexOf(':') < 0) c = TABLE.get("minecraft:" + stateName);
        return c == null ? FALLBACK_GRAY : c;
    }

